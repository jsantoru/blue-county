def weights(obj, bone=None, field=None):
    if field:
        for v in obj.data.vertices:
            for name,weight in field(v.co).items():
                if weight <= 0: continue
                group=obj.vertex_groups.get(name) or obj.vertex_groups.new(name=name)
                group.add([v.index],weight,'REPLACE')
    else:
        group=obj.vertex_groups.new(name=bone or 'torso'); group.add(list(range(len(obj.data.vertices))),1,'REPLACE')
    objects.append(obj); move_collection(obj)
    return obj

def mesh(name, vertices, faces, mat, bone=None, field=None, uvs=None):
    data=bpy.data.meshes.new(name); data.from_pydata(vertices,[],faces); data.update()
    obj=bpy.data.objects.new(name,data); collection.objects.link(obj); data.materials.append(mat)
    for poly in data.polygons: poly.use_smooth=True
    uv=data.uv_layers.new(name='UVMap')
    for poly in data.polygons:
        for li in poly.loop_indices:
            vi=data.loops[li].vertex_index
            p=data.vertices[vi].co
            uv.data[li].uv=uvs[vi] if uvs else (p.x*5,p.z*5)
    return weights(obj,bone,field)

def ellipsoid(name, location, scale, mat, bone='head', segments=32, rings=20, rotation=(0,0,0)):
    bpy.ops.mesh.primitive_uv_sphere_add(segments=segments,ring_count=rings,location=location)
    obj=bpy.context.object; obj.name=name; obj.scale=scale; obj.rotation_euler=rotation
    bpy.ops.object.transform_apply(location=True,rotation=True,scale=True)
    obj.data.materials.append(mat)
    for poly in obj.data.polygons: poly.use_smooth=True
    return weights(obj,bone)

def curve(name, points, radius, mat, bone='head', sides=4):
    data=bpy.data.curves.new(name,'CURVE'); data.dimensions='3D'; data.resolution_u=2
    data.bevel_depth=radius; data.bevel_resolution=1 if sides<=4 else 2
    poly=data.splines.new('POLY'); poly.points.add(len(points)-1)
    for q,p in zip(poly.points,points): q.co=(*p,1)
    obj=bpy.data.objects.new(name,data); collection.objects.link(obj); data.materials.append(mat)
    bpy.context.view_layer.objects.active=obj; obj.select_set(True)
    bpy.ops.object.convert(target='MESH'); obj=bpy.context.object; obj.select_set(False)
    for face in obj.data.polygons: face.use_smooth=True
    return weights(obj,bone)

def profile(z, rows):
    for index,(a,b) in enumerate(zip(rows,rows[1:])):
        if a[0] <= z <= b[0]:
            t=(z-a[0])/(b[0]-a[0]);span=b[0]-a[0]
            previous=rows[max(0,index-1)];following=rows[min(len(rows)-1,index+2)]
            values=[]
            for i in range(1,len(a)):
                ma=(b[i]-previous[i])/(b[0]-previous[0])*span
                mb=(following[i]-a[i])/(following[0]-a[0])*span
                values.append((2*t**3-3*t*t+1)*a[i]+(t**3-2*t*t+t)*ma+(-2*t**3+3*t*t)*b[i]+(t**3-t*t)*mb)
            return tuple(values)
    return rows[0][1:] if z<rows[0][0] else rows[-1][1:]

