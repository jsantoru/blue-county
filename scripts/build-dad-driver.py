def fabric(m, kind, size=512):
    import numpy as np
    rng=np.random.default_rng(1968 if kind=='checks' else 1948)
    y,x=np.mgrid[:size,:size]
    weave=(np.sin(x*pi)*.004 + np.sin(y*pi)*.004)
    noise=rng.normal(0,.018,(size,size))
    if kind=='checks':
        base=np.array([.37,.58,.75])
        period=size/8
        dx=np.minimum(x%period, period-x%period)
        dy=np.minimum(y%period, period-y%period)
        line=np.maximum(np.clip((1.5-dx)/1.5,0,1),np.clip((1.5-dy)/1.5,0,1))
        fine=np.maximum(np.clip((.7-abs(dx-4))/.7,0,1),np.clip((.7-abs(dy-4))/.7,0,1))
        rgb=base[None,None,:]*(1-.25*line[:,:,None]-.12*fine[:,:,None])+noise[:,:,None]*.36
    elif kind=='tweed':
        base=np.array([.09,.098,.105])
        direction=np.where((x//24)%2==0,1,-1)
        chevron=np.sin((x+direction*y)*pi/5)
        rgb=base[None,None,:]+(.022*chevron+noise*.8)[:,:,None]
    else:
        base=np.array([.09,.097,.105])
        rgb=base[None,None,:]+noise[:,:,None]*.36
    rgba=np.ones((size,size,4),dtype=np.float32)
    rgba[:,:,:3]=np.clip(rgb,0,1)
    image=bpy.data.images.new('Original baked '+kind, width=size,height=size)
    image.pixels.foreach_set(rgba.ravel()); image.pack()
    image['provenance']='Original procedural cotton/tweed pixels generated by build-dad-driver.py; no photographic pixels.'
    nodes=m.node_tree.nodes; texture=nodes.new('ShaderNodeTexImage'); texture.image=image
    texture.interpolation='Linear'; texture.extension='REPEAT'
    m.node_tree.links.new(texture.outputs['Color'],nodes.get('Principled BSDF').inputs['Base Color'])
    bump=nodes.new('ShaderNodeBump'); bump.inputs['Strength'].default_value=.13; bump.inputs['Distance'].default_value=.00025
    m.node_tree.links.new(texture.outputs['Color'],bump.inputs['Height'])
    m.node_tree.links.new(bump.outputs['Normal'],nodes.get('Principled BSDF').inputs['Normal'])
