def reach_wheel(label, side):
    """Bake a two-bone downward-elbow reach to the original steering wheel."""
    upper=rig.pose.bones[label+'_arm'];lower=rig.pose.bones[label+'_forearm']
    bpy.context.view_layer.update()
    shoulder=upper.head.copy();target=Vector((side*.145,-.357,.938))
    direction=target-shoulder;distance=direction.length;direction.normalize()
    a=upper.bone.length;b=lower.bone.length
    along=(a*a-b*b+distance*distance)/(2*distance)
    bend=Vector((side*.2,0,-1));bend-=direction*direction.dot(bend);bend.normalize()
    elbow=shoulder+direction*along+bend*sqrt(max(0,a*a-along*along))
    for bone,end in ((upper,elbow),(lower,target)):
        bpy.context.view_layer.update();head=bone.head.copy()
        rotation=(bone.tail-head).rotation_difference(end-head)
        bone.matrix=Matrix.Translation(head) @ rotation.to_matrix().to_4x4() @ Matrix.Translation(-head) @ bone.matrix
    bpy.context.view_layer.update()

